export type BlockEditorLabels = { [K in keyof (typeof BLOCK_EDITOR_MESSAGES)["en"]]: string };

let registered = false;

/** Idempotent: the first editor to render registers the three catalogues. */
export function ensureBlockEditorMessages(): void {
  if (registered) return;
  registered = true;
  for (const locale of ["ja", "en", "vi"] as const) {
    registerMessages(locale, { blockEditor: BLOCK_EDITOR_MESSAGES[locale] });
  }
}
