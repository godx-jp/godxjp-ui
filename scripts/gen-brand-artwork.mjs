#!/usr/bin/env node
/**
 * Embed the GoDX master logo SVGs into the package, VERBATIM (brand identity v2.3).
 *
 * The brand guidelines (`06_UI_Design_System/UI_UX_Guidelines.html`) are explicit, and an earlier
 * attempt broke all four of these rules by shipping the FLAT cut re-tinted by a token:
 *
 *   · "Logo master không bị nhuộm lại theo màu của một module."
 *   · "Logo dùng master SVG đúng biến thể sáng/tối."
 *   · "Dark asset: cung cấp biến thể phù hợp; không dùng filter đảo màu ảnh/logo."
 *   · "Không đổi hình G, wordmark, tỷ lệ vàng hoặc construction chỉ vì theme cần khác màu."
 *
 * So: both masters ship as-is — every gradient stop, the clipPath, the arrow fold — and the theme
 * selects a VARIANT rather than recolouring one. Nothing here edits geometry.
 *
 * The only transformation is ID NAMESPACING. Both variants are inlined in the same document, and
 * they use identical ids (`iconBodyGradient`, `arrowClip`, …); without a prefix the second copy's
 * `url(#…)` would resolve to the first copy's gradient and paint the wrong variant.
 */
import { readFileSync, writeFileSync } from "node:fs";

/** Replaced with a per-instance id at render time. See brand/godx-artwork.generated.ts. */
const ID_TOKEN = "__GXID__";

const KIT = process.argv[2];
if (!KIT) {
  console.error("usage: gen-brand-artwork.mjs <path to GoDX kit 01_GoDX/assets/logos>");
  process.exit(2);
}

/** Everything between <svg …> and </svg>, with defs ids namespaced so two copies can coexist. */
function inner(file, prefix) {
  const svg = readFileSync(`${KIT}/${file}`, "utf8");
  const body = svg.replace(/^[\s\S]*?<svg\b[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const ids = [...body.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  // The prefix is a PLACEHOLDER the component substitutes per instance. A fixed prefix is not
  // enough: ids are unique per DOCUMENT, not per file, so two <Logo>s on one page collide and
  // `url(#…)` resolves to whichever came first. Measured — removing the first logo leaves the
  // second with a dangling clipPath and a visibly broken mark.
  let out = body;
  for (const id of new Set(ids)) {
    out = out.replaceAll(`id="${id}"`, `id="${ID_TOKEN}-${prefix}-${id}"`);
    out = out.replaceAll(`url(#${id})`, `url(#${ID_TOKEN}-${prefix}-${id})`);
  }
  // <title>/<desc> belong to the standalone file; inline the artwork only.
  out = out.replace(/<title[\s\S]*?<\/title>/g, "").replace(/<desc[\s\S]*?<\/desc>/g, "");
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  return { markup: out.trim(), viewBox };
}

const variants = {
  lockupLight: inner("GoDX-logo-purple.svg", "gx-lockup-l"),
  lockupDark: inner("GoDX-logo-reverse.svg", "gx-lockup-d"),
  markLight: inner("GoDX-icon-purple.svg", "gx-mark-l"),
  markDark: inner("GoDX-icon-reverse.svg", "gx-mark-d"),
};

const ts = `// AUTO-GENERATED by scripts/gen-brand-artwork.mjs — do not hand-edit.
// Source: GoDX brand identity v2.3, 01_GoDX/assets/logos/*.svg, embedded verbatim.
//
// WHY VERBATIM AND WHY TWO VARIANTS: the brand guidelines forbid re-tinting the master and forbid
// inverting it with a filter; they require "master SVG đúng biến thể sáng/tối". So the light and
// dark artworks are both here, byte-for-byte apart from ID namespacing (both files use the same
// gradient ids, and two copies in one document would otherwise cross-resolve).
//
// Regenerate: node scripts/gen-brand-artwork.mjs <kit>/01_GoDX/assets/logos

export const GODX_ARTWORK_ID_TOKEN = "__GXID__";

export interface BrandArtwork {
  readonly viewBox: string;
  /** Inner SVG markup — package-owned static artwork, never user input. */
  readonly markup: string;
}

${Object.entries(variants)
  .map(
    ([name, v]) =>
      `export const GODX_${name.replace(/([A-Z])/g, "_$1").toUpperCase()}: BrandArtwork = Object.freeze({\n  viewBox: ${JSON.stringify(v.viewBox)},\n  markup: ${JSON.stringify(v.markup)},\n});`,
  )
  .join("\n\n")}
`;

writeFileSync("src/brand/godx-artwork.generated.ts", ts);
console.log(
  `wrote src/brand/godx-artwork.generated.ts (${Object.keys(variants).length} variants, ${ts.length} bytes)`,
);
