#!/usr/bin/env node
/**
 * Generates src/contracts/measurement.json — the machine-readable answer to "what box does this
 * library mean when it says a target is 24×24, and where does the --space-* scale stop applying".
 *
 * WHY THIS FILE EXISTS, IN NUMBERS. gh#503, gh#506 and gh#507 were each closed and reopened four
 * times across 23.0.0 → 23.4.5. Every reopening carried a correct measurement and every closing
 * carried a correct fix, because the two sides were measuring different boxes:
 *
 *   gh#507  consumer read 20×20   library ships a 24×24 target on a ::after
 *   gh#506  consumer read 24×13   library ships a 24×26 target on a ::after
 *   gh#503  consumer read 5.1px   library derives that 5.1 from the control band, not --space-*
 *
 * `getBoundingClientRect()` returns the element's border box, and a border box does not include an
 * absolutely-positioned pseudo-element. WCAG 2.2 SC 2.5.8 measures the TARGET — the region that
 * accepts the pointer action — and carrying it on a pseudo-element is the technique its
 * Understanding document names. So a consumer gate built on `getBoundingClientRect` reports the
 * same number forever, no matter what the library ships, and cannot tell "fixed" from "ignored".
 *
 * Prose could not close that gap: `docs/SPACING.md` had said the gh#503 derivation since 23.4.0 and
 * the issue was reopened twice afterwards, because a gate cannot read prose. So the facts ship as
 * DATA, in the package, at `dist/contracts/measurement.json`, for any language to read.
 *
 * DERIVED, NOT DECLARED. The expander list is parsed out of `src/styles/*.css` rather than typed
 * here, because a hand-kept list is exactly the failure this contract exists to end — a fact that
 * grep confirms and measurement denies. `--check` fails the build when the CSS moves and the
 * contract does not, and `scripts/check-measurement-contract.mjs` then proves every entry in a real
 * browser, so the contract cannot claim a target the library does not actually ship.
 */
import { readFileSync, writeFileSync, mkdirSync, globSync } from "node:fs";

const OUT = "src/contracts/measurement.json";

/** The floor, and the standard that sets it. Mirrors --touch-target-min in src/tokens/foundation.css. */
const TARGET_MIN = 24;

/** Strip comments before matching, or a rule's prose joins its selector. */
function decomment(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, "");
}

/**
 * Every rule that raises a target to --touch-target-min, keyed by the CONTROL it applies to.
 *
 * Two shapes, and the second was missed at first (gh#626). A control with no real input carries its
 * target on a pseudo-element — `.ui-control-inline-affix-action::after`. A control that HAS one
 * carries it on that input instead — `.ui-switch > .ui-choice-input` — because a pseudo-element on
 * the label would sit on top of the input and `elementFromPoint` would stop returning it. Both are
 * "the target is bigger than this selector's border box", which is the only thing a consumer gate
 * needs to know, so both belong in the contract. Parsing only `::after` published one and hid the
 * other, and a reporter measuring `label.ui-switch` read 20px with nothing in the file to explain it.
 */
function parseExpanders(file, css) {
  const found = [];
  for (const [, selector, body] of decomment(css).matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    if (!body.includes("--touch-target-min")) continue;
    const sel = selector.trim().replace(/\s+/g, " ");
    // `.ui-x::after` / `.ui-x::before` — the target rides a pseudo-element.
    const pseudo = /^(\.[\w-]+)::(after|before)$/.exec(sel);
    if (pseudo) {
      found.push({ selector: pseudo[1], via: `::${pseudo[2]}`, source: file });
      continue;
    }
    // `.ui-x > .child` / `.ui-x .child` — the target rides a real descendant (an <input>).
    const descendant = /^(\.[\w-]+)\s*[>\s]\s*(\S+)$/.exec(sel);
    if (descendant) {
      found.push({ selector: descendant[1], via: descendant[2], source: file });
    }
  }
  return found;
}

/** Which shipped components actually render a class, so a reader knows what they are looking at. */
function componentsUsing(className) {
  const bare = className.replace(/^\./, "");
  const names = new Set();
  for (const file of globSync("src/components/**/*.tsx")) {
    if (file.includes("__tests__")) continue;
    if (!readFileSync(file, "utf8").includes(bare)) continue;
    names.add(
      file
        .split("/")
        .pop()
        .replace(/\.tsx$/, ""),
    );
  }
  return [...names].sort();
}

const expanders = globSync("src/styles/*.css")
  .sort()
  .flatMap((file) => parseExpanders(file, readFileSync(file, "utf8")))
  .map((e) => ({ ...e, targetMin: TARGET_MIN, components: componentsUsing(e.selector) }))
  .sort((a, b) => a.selector.localeCompare(b.selector));

const contract = {
  $comment:
    "AUTO-GENERATED by scripts/gen-measurement-contract.mjs — do not edit. " +
    "Read this instead of guessing: docs/MEASUREMENT-CONTRACT.md.",
  version: JSON.parse(readFileSync("package.json", "utf8")).version,
  targetSize: {
    standard: "WCAG 2.2 SC 2.5.8 Target Size (Minimum), level AA — 24×24 CSS px",
    min: TARGET_MIN,
    measures: "target",
    note:
      "The TARGET is the region that accepts the pointer action, which is not always the painted " +
      "box. getBoundingClientRect() returns the border box and cannot see a pseudo-element, so it " +
      "UNDER-REPORTS every selector listed under `expanders`. Measure with elementFromPoint — see " +
      "`method` — or treat a listed selector as conforming at `targetMin`.",
    method: "docs/MEASUREMENT-CONTRACT.md#measuring-a-target",
    expanders,
  },
  spacing: {
    scale: "--space-* measures the distance BETWEEN things: page sections, siblings, a Card and its content.",
    doesNotApplyTo:
      "The INTERIOR of a control. That geometry is derived from the control band, not from --space-*, " +
      "so a control's own label sits closer to its edge than --space-2 and is not a finding.",
    derivation: "interior height = --control-height − (interior padding × 2)",
    predicate:
      "An element is a control when its painted block-size equals the resolved --control-height for " +
      "its size. Segmented's track, Button, Input and Select all satisfy it — a gate that applies a " +
      "--space-* floor inside a control flags all four, not just Segmented.",
    reference: "docs/SPACING.md#control-interiors-are-not-on-this-scale",
  },
  issues: {
    503: "Segmented track padding read against a --space-2 floor that does not govern control interiors.",
    506: "NumberInput steppers read as 24×13 (paint); the target is 24×26.",
    507: "DatePicker calendar button read as 20×20 (paint); the target is 24×24.",
  },
};

const body = `${JSON.stringify(contract, null, 2)}\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    /* missing → stale */
  }
  if (current !== body) {
    console.error(
      `✗ check:measurement-contract — ${OUT} is stale. Run \`node scripts/gen-measurement-contract.mjs\`.`,
    );
    // NAME WHAT MOVED. A consumer gate keys off these selectors; "the file is stale" sends a reader
    // to a diff, while the two lines below are the whole story when a target is added or dropped.
    let previous = [];
    try {
      previous = JSON.parse(current).targetSize.expanders.map((e) => e.selector);
    } catch {
      /* unparseable → treat as empty */
    }
    const now = expanders.map((e) => e.selector);
    const added = now.filter((s) => !previous.includes(s));
    const removed = previous.filter((s) => !now.includes(s));
    if (added.length) console.error(`    + expanded target(s): ${added.join(", ")}`);
    if (removed.length) console.error(`    − target(s) no longer expanded: ${removed.join(", ")}`);
    if (!added.length && !removed.length)
      console.error("    same selectors — the version or a description moved");
    process.exit(1);
  }
  console.log(
    `✓ check:measurement-contract — ${expanders.length} expanded targets published for consumer gates.`,
  );
} else {
  mkdirSync("src/contracts", { recursive: true });
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT} (${expanders.length} expanded targets)`);
}
