#!/usr/bin/env node
/**
 * Renders EVERY /frame/** contract example in real Chromium at desktop (1440×900) and mobile-sm
 * (375×667) and runs axe-core on each. Three independently-tracked axe scopes per frame/viewport: •
 * PREVIEW CHROME = the zoom/dimension toolbar (`.demo-block-toolbar`). • COMPONENT = everything
 * else, in the frame's DEFAULT state. • OVERLAY = the same scope re-measured after performing the
 * frame's DECLARED open step (`data-axe-open`, see `openDeclaredOverlay`) — the state in which
 * `aria-hidden-focus` & friends exist at all (#355).
 */
import { writeFileSync, mkdirSync, readFileSync, existsSync } from "node:fs";
import path from "node:path";
import {
  DEFAULT_BASE,
  AXE_VIEWPORTS,
  REPO_ROOT,
  resolveChromiumExecutable,
  loadDeps,
  ensurePreviewServer,
  loadManifest,
  componentFrames,
} from "./frame-harness.mjs";

const BASELINE_PATH = path.join(REPO_ROOT, "scripts/frame-axe.baseline.json");
const EVIDENCE_DIR = path.join(REPO_ROOT, "audit-evidence/frame-axe");

const args = process.argv.slice(2);
const asJson = args.includes("--format") && args[args.indexOf("--format") + 1] === "json";
const updateBaseline = args.includes("--update-baseline");
const base = (args.find((a) => a.startsWith("http")) || DEFAULT_BASE).replace(/\/$/, "");
const limit = Number(process.env.AXE_FRAMES_LIMIT) || 0;

const C = {
  red: "\x1b[31m",
  green: "\x1b[32m",
  yellow: "\x1b[33m",
  dim: "\x1b[2m",
  bold: "\x1b[1m",
  reset: "\x1b[0m",
};
const log = (...a) => !asJson && console.log(...a);

/** Config error: nothing has been launched yet, so say what is wrong and stop. */
function bail(message) {
  if (asJson) process.stdout.write(JSON.stringify({ status: "error", message }) + "\n");
  else console.error(`✗ ${message}`);
  process.exit(2);
}

/**
 * Optional CI fan-out: `AXE_SHARD=i/n` (1-based) runs only shard i of n.
 *
 * The partition is taken over frame ids sorted by CODE POINT — a stable order that does not
 * depend on manifest / directory read order, so the same tree always yields the same partition
 * and every frame lands in exactly one shard. Unset ⇒ the frame list is untouched.
 */
function parseShard(raw) {
  if (!raw) return null;
  const m = /^(\d+)\s*\/\s*(\d+)$/.exec(raw.trim());
  if (!m) bail(`AXE_SHARD must look like "2/4" (1-based i/n) — got "${raw}"`);
  const index = Number(m[1]);
  const total = Number(m[2]);
  if (total < 1 || index < 1 || index > total)
    bail(`AXE_SHARD "${raw}" is out of range — expected 1 ≤ i ≤ n and n ≥ 1`);
  return { index, total };
}

const shard = parseShard(process.env.AXE_SHARD);
if (shard && updateBaseline) {
  // A shard sees a FRACTION of the frames. Writing the baseline from that would delete every
  // frame the shard did not visit — the baseline must only ever be regenerated by a full sweep.
  bail("--update-baseline cannot run under AXE_SHARD — regenerate the baseline in a full sweep.");
}

/** Partition `frames` for this shard, or return them untouched when unsharded. */
function applyShard(frames) {
  if (!shard) return frames;
  const ordered = [...frames].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return ordered.filter((_, i) => i % shard.total === shard.index - 1);
}

function loadBaseline() {
  if (!existsSync(BASELINE_PATH)) return { component: {} };
  try {
    return JSON.parse(readFileSync(BASELINE_PATH, "utf8"));
  } catch {
    return { component: {} };
  }
}

/**
 * DOM contract for the declared open step (#355).
 *
 * A frame opts into the overlay scope by putting `data-axe-open` on the trigger it wants pressed
 * — or, when the component owns its own trigger DOM and forwards no `data-*` to it (DatePicker,
 * the data-driven Select, SearchSelect), on the nearest element that DOES forward, with the gate
 * resolving the real control inside it. `data-axe-open="contextmenu"` right-clicks the declaring
 * element instead (ContextMenu opens on no other gesture).
 */
const OPEN_DECLARATION = "[data-axe-open]";
/** Controls a press can open an overlay from. Deliberately narrow — see the resolution above. */
const OPEN_TARGET =
  'button, [role="button"], [role="combobox"], [role="menuitem"], a[href], summary';
/** An overlay that has actually mounted: Radix portals every one of these. */
const OVERLAY_MOUNTED =
  '[data-radix-popper-content-wrapper], [role="dialog"], [role="alertdialog"], [role="menu"], [role="listbox"]';

/**
 * Viewports the overlay pass runs at. Only the frames that declare an open step pay for it, so
 * both viewports are affordable today (measured: +~1 min on a ~11 min sweep). If the number of
 * declaring frames grows to where that stops being true, narrow this to `["desktop"]` — an
 * overlay is portalled to `<body>` and its aria-hidden background is the same tree at either
 * width, so the second viewport buys less here than it does for the component scope.
 */
const OVERLAY_VIEWPORTS = new Set(AXE_VIEWPORTS.map((v) => v.id));

/**
 * Perform the frame's declared open step. Returns false when the frame declares none (the vast
 * majority), true once an overlay has actually mounted. Throws when a declaration exists but the
 * overlay never appeared — a broken declaration is a broken gate, not a silent skip.
 */
async function openDeclaredOverlay(page) {
  const decl = page.locator(OPEN_DECLARATION).first();
  if ((await decl.count()) === 0) return false;
  // JSX `data-axe-open` (no value) renders as "true"; only `contextmenu` selects a gesture.
  const gesture =
    (await decl.getAttribute("data-axe-open")) === "contextmenu" ? "contextmenu" : "click";
  // Several demos deliberately render an overlay OPEN at rest (Dialog/Sheet/Popover "shown open").
  // A modal one makes the rest of the page inert, so the declared trigger cannot be pressed while
  // it stands. Dismiss what is open first: the open step then always measures a real closed→open
  // transition rather than whatever the demo happened to leave mounted.
  for (let i = 0; i < 3 && (await page.locator(OVERLAY_MOUNTED).count()) > 0; i++) {
    await page.keyboard.press("Escape");
    await page.waitForTimeout(250);
  }
  const isTarget = await decl.evaluate((el, sel) => el.matches(sel), OPEN_TARGET);
  const target = gesture === "contextmenu" || isTarget ? decl : decl.locator(OPEN_TARGET).first();
  const before = await page.locator(OVERLAY_MOUNTED).count();
  await target.click({
    button: gesture === "contextmenu" ? "right" : "left",
    timeout: 10_000,
  });
  // Settle on the OVERLAY, not on a timer: wait until one more overlay is mounted than before the
  // press, then let the open animation finish so axe does not measure a half-transitioned tree.
  await page.waitForFunction(
    ({ sel, n }) => document.querySelectorAll(sel).length > n,
    { sel: OVERLAY_MOUNTED, n: before },
    { timeout: 8_000 },
  );
  await page.waitForTimeout(400);
  return true;
}

/** Run axe on a scope and return [{ id, impact, nodes }]. */
async function scan(AxeBuilder, page, { include, exclude }) {
  let b = new AxeBuilder({ page });
  if (include) b = b.include(include);
  if (exclude) b = b.exclude(exclude);
  const { violations } = await b.analyze();
  return violations.map((v) => ({ id: v.id, impact: v.impact, nodes: v.nodes.length }));
}

async function main() {
  let deps;
  try {
    deps = await loadDeps();
  } catch (cause) {
    const msg = "check:frame-axe needs optional peers `playwright` + `@axe-core/playwright`";
    if (asJson) process.stdout.write(JSON.stringify({ status: "error", message: msg }) + "\n");
    else console.warn(`⚠ ${msg} — skipped. (${cause.message})`);
    return; // skip in a browser-less env rather than fail the build
  }
  const { chromium, AxeBuilder } = deps;

  // No initialiser: the catch below returns, so past this point stopServer is always the
  // real teardown returned by ensurePreviewServer.
  let stopServer;
  try {
    stopServer = await ensurePreviewServer(base);
  } catch (e) {
    if (asJson)
      process.stdout.write(JSON.stringify({ status: "error", message: e.message }) + "\n");
    // A preview that will not start is a BROKEN GATE, not a gate with nothing to do. Skipping it
    // let three browser gates report success on CI for weeks while never once loading a page —
    // and that green is what made me spend six rounds asking why the OTHER shards were red, when
    // none of them had ever worked. `CI=true` is the honest line: locally a missing browser or a
    // busy port is a reason to step aside, but on CI it is the failure itself.
    if (process.env.CI) throw e;
    else console.warn(`⚠ check:frame-axe skipped — ${e.message}.`);
    return;
  }

  const execPath = resolveChromiumExecutable();
  const browser = await chromium.launch(execPath ? { executablePath: execPath } : {});
  // @axe-core/playwright 4.10+ requires the context→page flow (browser.newPage() throws).
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await context.newPage();

  let frames;
  try {
    const manifest = await loadManifest(page, base);
    frames = componentFrames(manifest);
  } catch (e) {
    await browser.close();
    stopServer();
    if (asJson)
      process.stdout.write(JSON.stringify({ status: "error", message: e.message }) + "\n");
    else console.error(`✗ ${e.message}`);
    process.exit(2);
  }
  if (limit) frames = frames.slice(0, limit);
  frames = applyShard(frames);

  const baseline = loadBaseline();
  const results = [];
  const chromeHits = []; // { frame, viewport, rule, impact, nodes }
  const componentCurrent = {}; // frameId → viewport → rule → nodes
  const overlayCurrent = {}; // frameId → viewport → rule → nodes (overlay OPEN)
  const overlayRan = new Set(); // frames whose declared open step actually ran
  const infraErrors = [];

  // Baseline generation can UNION several passes (AXE_RUNS>1) so intermittently-mounted
  // portals are captured — a rule-set the gate then never falsely regresses on. The gate
  // itself runs a single pass (a NEW rule outside the union baseline is a genuine problem).
  const RUNS = Math.max(1, Number(process.env.AXE_RUNS) || (updateBaseline ? 2 : 1));
  log(
    `· axe over ${frames.length} frame(s) × ${AXE_VIEWPORTS.length} viewport(s)` +
      `${RUNS > 1 ? ` × ${RUNS} pass(es)` : ""}` +
      `${shard ? ` — shard ${shard.index}/${shard.total}` : ""}…`,
  );
  let done = 0;
  for (let run = 0; run < RUNS; run++) {
    for (const frame of frames) {
      const record = { id: frame.id, viewports: {} };
      for (const vp of AXE_VIEWPORTS) {
        await page.setViewportSize({ width: vp.width, height: vp.height });
        const url = `${base}/frame/${encodeURIComponent(frame.id)}`;
        try {
          await page.goto(url, { waitUntil: "networkidle", timeout: 30_000 });
          // Let Radix portals (Dialog/Popover/Sheet content) finish mounting so a demo's
          // overlay is consistently present at axe time — reduces open/closed count jitter.
          await page.waitForTimeout(800);
        } catch (e) {
          infraErrors.push({ frame: frame.id, viewport: vp.id, message: e.message.split("\n")[0] });
          continue;
        }
        let chrome, comp;
        try {
          // Chrome = the preview toolbar we own (zoom/dimension controls). Component/demo =
          // EVERYTHING else — the rendered frame AND Radix-portaled content (Dialog/Popover/
          // Sheet/Toast/Select) which mounts on document.body OUTSIDE `.demo-block-frame`.
          // Scoping component by `exclude(.demo-block-toolbar)` (not `include(.demo-block-frame)`)
          // keeps portaled demo violations attributed to the component, never to chrome.
          chrome = await scan(AxeBuilder, page, { include: ".demo-block-toolbar" });
          comp = await scan(AxeBuilder, page, { exclude: ".demo-block-toolbar" });
        } catch (e) {
          infraErrors.push({ frame: frame.id, viewport: vp.id, message: `axe: ${e.message}` });
          continue;
        }
        for (const v of chrome) chromeHits.push({ frame: frame.id, viewport: vp.id, ...v });
        for (const v of comp) {
          ((componentCurrent[frame.id] ??= {})[vp.id] ??= {})[v.id] ??= 0;
          componentCurrent[frame.id][vp.id][v.id] += v.nodes;
        }
        record.viewports[vp.id] = { chrome, component: comp };

        // ---- Overlay scope: the state this gate could never see before (#355) -----------
        // Runs LAST on the page, because opening an overlay is destructive to the default
        // state the two scopes above measure. Only frames that declare an open step pay for it.
        if (OVERLAY_VIEWPORTS.has(vp.id)) {
          try {
            if (await openDeclaredOverlay(page)) {
              overlayRan.add(frame.id);
              const open = await scan(AxeBuilder, page, { exclude: ".demo-block-toolbar" });
              for (const v of open) {
                ((overlayCurrent[frame.id] ??= {})[vp.id] ??= {})[v.id] ??= 0;
                overlayCurrent[frame.id][vp.id][v.id] += v.nodes;
              }
              record.viewports[vp.id].overlay = open;
            }
          } catch (e) {
            infraErrors.push({
              frame: frame.id,
              viewport: vp.id,
              message: `overlay open: ${e.message.split("\n")[0]}`,
            });
          }
        }
      }
      if (run === 0) results.push(record);
      done++;
      if (!asJson && done % 20 === 0) log(`  …${done}/${frames.length * RUNS}`);
    }
  }

  await browser.close();
  stopServer();

  // Rule-PRESENCE per frame (union across viewports). We allowlist violation *types* per
  // frame, not exact node counts: axe counts jitter run-to-run (a Radix portal open vs
  // closed changes a count by ±1) which would make an exact-count gate flaky. A rule
  // leaving a frame's set is a real fix (shrink); a NEW rule on a frame is a real
  // Node counts are still recorded in the evidence JSON for triage.
  const runFrameIds = new Set(frames.map((f) => f.id));

  /** frameId → viewport → rule → nodes  ⇒  { rules: fid → [ruleId], total: nodeCount }. */
  function ruleSets(byFrame) {
    const rules = {};
    let total = 0;
    for (const fid of Object.keys(byFrame)) {
      const set = new Set();
      for (const vp of Object.keys(byFrame[fid])) {
        for (const [rule, n] of Object.entries(byFrame[fid][vp])) {
          set.add(rule);
          total += n;
        }
      }
      if (set.size) rules[fid] = [...set].sort();
    }
    return { rules, total };
  }

  const { rules: currentRules, total: componentTotal } = ruleSets(componentCurrent);
  const { rules: overlayRules, total: overlayTotal } = ruleSets(overlayCurrent);

  // ---- Baseline update mode -------------------------------------------------
  if (updateBaseline) {
    // Merge: overwrite the frames we actually ran, keep others — so a limited
    // `AXE_FRAMES_LIMIT=… --update-baseline` never silently drops un-run frames.
    const sorted = (o) =>
      Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : 1)));
    const rebuild = (previous, fresh, visited) => {
      const merged = { ...(previous ?? {}) };
      for (const fid of visited) {
        if (fresh[fid]) merged[fid] = fresh[fid];
        else delete merged[fid]; // ran and is now clean → remove from allowlist
      }
      return sorted(merged);
    };
    // The OVERLAY allowlist may only be rewritten for frames whose open step actually ran: a
    // frame that no longer declares one has not been proven clean, it has been left unmeasured.
    const component = rebuild(baseline.component, currentRules, runFrameIds);
    const overlay = rebuild(baseline.overlay, overlayRules, overlayRan);
    // #356 — REBUILDING MUST NOT EAT THE PROSE. This file also carries human notes (`scopeGap`:
    // what the gate still cannot see, and why some violations are deliberately unfixed). Writing
    // the file from scratch silently deleted them. Every key the gate does not own is carried
    // over verbatim and named in the log, so a key can never disappear unnoticed.
    const OWNED = new Set(["generatedAt", "note", "component", "overlay"]);
    const carried = Object.fromEntries(Object.entries(baseline).filter(([k]) => !OWNED.has(k)));
    const out = {
      generatedAt: new Date().toISOString().slice(0, 10),
      note:
        "Per-frame axe allowlists. `component` = violations in the frame's DEFAULT state " +
        "(inside the rendered frame + its portals); `overlay` = the same scope re-measured " +
        "after the frame's declared `data-axe-open` step, i.e. with an overlay OPEN. Each " +
        "value is the set of axe rule ids still firing on that frame. Both may only SHRINK — " +
        "a new rule on a frame fails CI. Chrome (the preview toolbar) is NOT allowlisted: it " +
        "must be 0. Keys other than these are human notes and are preserved verbatim across " +
        "`--update-baseline`. Regenerate after a component-fix PR merges: " +
        "`node scripts/check-frame-axe.mjs --update-baseline`.",
      ...carried,
      component,
      overlay,
    };
    writeFileSync(BASELINE_PATH, JSON.stringify(out, null, 2) + "\n");
    log(
      `✓ baseline written → ${path.relative(REPO_ROOT, BASELINE_PATH)} ` +
        `(${Object.keys(component).length} frame(s) with component violations, ` +
        `${Object.keys(overlay).length} with overlay violations; ` +
        `carried over: ${Object.keys(carried).join(", ") || "(no extra keys)"}).`,
    );
    return;
  }

  // ---- Compare rule-sets to baseline (run frames only) ----------------------
  // A shard sees only part of the frame list. "New rule on a frame" stays exact under sharding
  // (the baseline is keyed per frame); "rule no longer fires" does NOT — a frame the shard never
  // visited is missing, not fixed — so shrink hints are only collected on a full sweep.
  const regressions = []; // NEW rule on a frame → blocking
  const shrinkHints = []; // rule gone from a frame → baseline can be tightened
  const overlayRegressions = [];
  const overlayShrinkHints = [];
  const compare = (baseMap, fresh, visited, intoRegressions, intoShrink) => {
    for (const fid of visited) {
      const cur = new Set(fresh[fid] ?? []);
      // Baseline schema is `fid → [ruleId]`. Guard against a stale/foreign shape so a
      // schema drift degrades to "no allowlist for this frame" instead of crashing.
      const base_ = new Set(Array.isArray(baseMap[fid]) ? baseMap[fid] : []);
      for (const rule of cur) if (!base_.has(rule)) intoRegressions.push({ frame: fid, rule });
      if (shard) continue;
      for (const rule of base_) if (!cur.has(rule)) intoShrink.push({ frame: fid, rule });
    }
  };
  compare(baseline.component ?? {}, currentRules, runFrameIds, regressions, shrinkHints);
  // Only frames whose open step ran are compared: an un-declared frame has nothing to say about
  // the overlay allowlist in either direction.
  compare(baseline.overlay ?? {}, overlayRules, overlayRan, overlayRegressions, overlayShrinkHints);

  // ---- Aggregate chrome by rule --------------------------------------------
  const chromeByRule = {};
  for (const h of chromeHits) {
    chromeByRule[h.id] ??= { impact: h.impact, nodes: 0, frames: new Set() };
    chromeByRule[h.id].nodes += h.nodes;
    chromeByRule[h.id].frames.add(`${h.frame}@${h.viewport}`);
  }
  const chromeFail = chromeHits.length > 0;
  const regressionFail = regressions.length > 0;
  const overlayFail = overlayRegressions.length > 0;
  const pass = !chromeFail && !regressionFail && !overlayFail && infraErrors.length === 0;

  const summary = {
    status: pass ? "ok" : "fail",
    frames: frames.length,
    shard: shard ? `${shard.index}/${shard.total}` : null,
    viewports: AXE_VIEWPORTS.map((v) => v.id),
    chromeViolations: chromeHits.reduce((n, h) => n + h.nodes, 0),
    componentViolations: componentTotal,
    componentRegressions: regressions.length,
    overlayFrames: overlayRan.size,
    overlayViolations: overlayTotal,
    overlayRegressions: overlayRegressions.length,
    infrastructureErrors: infraErrors.length,
  };

  // ---- Evidence -------------------------------------------------------------
  mkdirSync(EVIDENCE_DIR, { recursive: true });
  const evidence = {
    generatedAt: new Date().toISOString(),
    base,
    summary,
    chrome: Object.fromEntries(
      Object.entries(chromeByRule).map(([k, v]) => [
        k,
        { impact: v.impact, nodes: v.nodes, frames: [...v.frames] },
      ]),
    ),
    componentCurrent,
    regressions,
    shrinkHints,
    overlayCurrent,
    overlayFrames: [...overlayRan].sort(),
    overlayRegressions,
    overlayShrinkHints,
    infraErrors,
    results,
  };
  writeFileSync(
    path.join(EVIDENCE_DIR, "frame-axe-results.json"),
    JSON.stringify(evidence, null, 2) + "\n",
  );

  if (asJson) {
    process.stdout.write(JSON.stringify(evidence, null, 2) + "\n");
    process.exit(pass ? 0 : 1);
  }

  // ---- Human report ---------------------------------------------------------
  log(`\n${C.bold}Preview-chrome axe (blocking — must be 0):${C.reset}`);
  if (!chromeFail) {
    log(`  ${C.green}✓ 0 chrome violations across all ${frames.length} frame(s).${C.reset}`);
  } else {
    for (const [rule, v] of Object.entries(chromeByRule)) {
      log(
        `  ${C.red}✗ ${rule} (${v.impact}) — ${v.nodes} node(s) in ${v.frames.size} frame/viewport run(s)${C.reset}`,
      );
      log(`      e.g. ${[...v.frames].slice(0, 4).join(", ")}`);
    }
  }

  log(`\n${C.bold}Component/demo axe (allowlisted — baseline may only shrink):${C.reset}`);
  log(
    `  ${componentTotal} component violation node(s) remaining across ${Object.keys(componentCurrent).length} frame(s).`,
  );
  if (regressionFail) {
    log(`  ${C.red}✗ ${regressions.length} NEW violation-type(s) not in baseline:${C.reset}`);
    for (const r of regressions.slice(0, 40)) log(`      ${C.red}${r.frame}: ${r.rule}${C.reset}`);
  } else {
    log(`  ${C.green}✓ no new component violation types (rule-set within baseline).${C.reset}`);
  }
  if (shrinkHints.length) {
    log(
      `  ${C.yellow}↓ ${shrinkHints.length} baseline rule(s) no longer fire (component agents fixed them) — run --update-baseline to tighten:${C.reset}`,
    );
    for (const s of shrinkHints.slice(0, 25)) log(`      ${s.frame}: ${s.rule}`);
  }
  log(
    `\n${C.bold}Overlay axe (frames declaring data-axe-open — baseline may only shrink):${C.reset}`,
  );
  log(
    `  ${overlayRan.size} frame(s) opened an overlay before scanning; ` +
      `${overlayTotal} violation node(s) while open.`,
  );
  if (overlayFail) {
    log(
      `  ${C.red}✗ ${overlayRegressions.length} NEW violation-type(s) not in the overlay baseline:${C.reset}`,
    );
    for (const r of overlayRegressions.slice(0, 40))
      log(`      ${C.red}${r.frame}: ${r.rule}${C.reset}`);
  } else {
    log(`  ${C.green}✓ no new overlay violation types (rule-set within baseline).${C.reset}`);
  }
  if (overlayShrinkHints.length) {
    log(
      `  ${C.yellow}↓ ${overlayShrinkHints.length} overlay baseline rule(s) no longer fire — run --update-baseline to tighten:${C.reset}`,
    );
    for (const s of overlayShrinkHints.slice(0, 25)) log(`      ${s.frame}: ${s.rule}`);
  }
  if (shard) {
    log(
      `  ${C.dim}(shard ${shard.index}/${shard.total}: “no longer fires” checks are skipped — ` +
        `only a full sweep can tell a fixed frame from an unvisited one.)${C.reset}`,
    );
  }
  if (infraErrors.length) {
    log(`\n${C.red}Infrastructure errors (${infraErrors.length}):${C.reset}`);
    for (const e of infraErrors.slice(0, 20)) log(`  ${e.frame}@${e.viewport}: ${e.message}`);
  }

  log(
    `\nevidence → ${path.relative(REPO_ROOT, path.join(EVIDENCE_DIR, "frame-axe-results.json"))}`,
  );
  if (pass) {
    log(
      `\n${C.green}✓ check:frame-axe — chrome AA clean; component + overlay violations within allowlist.${C.reset}`,
    );
    process.exit(0);
  }
  log(
    `\n${C.red}✗ check:frame-axe FAILED${C.reset} — ` +
      `${chromeFail ? "preview-chrome has a11y violations; " : ""}` +
      `${regressionFail ? "component violations regressed above baseline; " : ""}` +
      `${overlayFail ? "overlay-open violations regressed above baseline; " : ""}` +
      `${infraErrors.length ? "some frames failed to load." : ""}`,
  );
  process.exit(1);
}

main().catch((e) => {
  console.error(e);
  process.exit(2);
});
