#!/usr/bin/env node
/**
 * gen-frame-coverage-ledger — regenerate preview/frame-coverage.ledger.json (issue #163 item 1).
 *
 * The ledger is GENERATED from the real public surface, never hand-listed:
 *
 *   component barrels  → scripts/check-frame-coverage.mjs (export ↔ owning /frame route)
 *   TypeScript API     → component-api-manifest.json      (which dimensions even APPLY)
 *   executed evidence  → component-case-evidence.json     (the only auto-promotion input)
 *   authored cases     → the ledger's own `cases` array   (reviewed, resolvable, ratcheted)
 *
 * Hand-authored inputs (`policy.notApplicable`, `cases`, `policy.knownGaps[].resolvedBy`) are
 * PRESERVED across regeneration; everything else is recomputed. A verdict therefore cannot be
 * faked by editing the ledger: `covered` only appears when an evidence chain resolves on disk.
 *
 * Per-export ratchet baselines are tightened automatically (reasoned-N/A may only fall, covered
 * may only rise) — that is what makes the gate "baseline-locked, extendable, never weakenable".
 *
 * Usage:
 *   node scripts/gen-frame-coverage-ledger.mjs                   # write
 *   node scripts/gen-frame-coverage-ledger.mjs --check           # CI staleness check
 *   node scripts/gen-frame-coverage-ledger.mjs --reset-baseline  # re-mint the ratchet floor
 *
 * `--reset-baseline` is the deliberate, auditable escape hatch (same convention as
 * `frame-geometry.mjs --update-baseline`): it re-mints the floor from CURRENT reality instead of
 * keeping the tightest value ever seen. Use it only when introducing the ledger, or after a
 * reviewed public-API change legitimately turns a dimension into a reasoned N/A. Never use it to
 * silence a coverage regression — that is precisely what the gate exists to catch.
 */
import fs from "node:fs";
import path from "node:path";
import {
  AXES,
  DIMENSIONS,
  DIMENSION_IDS,
  EMBEDDABLE_EXPORTS,
  KNOWN_GAPS,
  LEDGER_PATH,
  LEDGER_SCHEMA_VERSION,
  REPO_ROOT,
  REQUIRED_CONTAINER_WIDTHS,
  REQUIRED_VIEWPORTS,
  RUNTIME_GATE_SCRIPTS,
  axeSweep,
  deriveComponents,
  geometrySweep,
  loadApiManifest,
  loadCaseEvidence,
  loadDiscovery,
  readJson,
  totalsFor,
  validateCase,
} from "./frame-coverage-contract.mjs";

const check = process.argv.includes("--check");
const resetBaseline = process.argv.includes("--reset-baseline");
const MCP_DATA_PATH = path.join(REPO_ROOT, "mcp/src/data/frame-coverage.generated.ts");

/**
 * Emit the MCP-side coverage catalogue (issue #163 item 7). Consuming agents must be able to
 * ask "is this state actually proven?" and get UNTESTED — never a happy-path example presented
 * as evidence of support.
 */
function renderMcpData(ledger, rows, totals) {
  const entries = rows.map((row) => {
    const bucket = (status) =>
      DIMENSION_IDS.filter((id) => row.dimensions[id].status === status).sort();
    return {
      name: row.export,
      group: row.group,
      frame: row.frames[0] ?? null,
      covered: bucket("covered"),
      untested: bucket("untested"),
      notApplicable: bucket("not-applicable"),
    };
  });
  const lines = [
    "/**",
    " * GENERATED by scripts/gen-frame-coverage-ledger.mjs — DO NOT EDIT.",
    " *",
    " * Preview-contract coverage per public export (issue #163). This is what lets an agent",
    ' * answer "is this state actually proven?" instead of trusting a hand-picked example.',
    " *",
    " * READ THIS BEFORE USING IT: `untested` is NOT a pass and NOT a failure — it means no",
    " * executed case demonstrates that dimension. Never infer that a component supports a",
    " * variant, state, viewport, direction, keyboard interaction or async lifecycle because an",
    " * example renders. The absence of a demonstrated state is never evidence of support.",
    " */",
    "",
    "export type FrameCoverageDimension =",
    ...DIMENSION_IDS.map(
      (id, index) => `  | "${id}"${index === DIMENSION_IDS.length - 1 ? ";" : ""}`,
    ),
    "",
    "export interface FrameCoverageEntry {",
    "  /** Public export name. */",
    "  name: string;",
    "  group: string;",
    "  /** Repository path of the frame that renders it, or null when no frame exists yet. */",
    "  frame: string | null;",
    "  /** Dimensions proven by an executed case. */",
    "  covered: FrameCoverageDimension[];",
    "  /** Dimensions with NO executed case. UNTESTED — never read as supported. */",
    "  untested: FrameCoverageDimension[];",
    "  /** Dimensions that cannot exist for this export, each with a written reason in the ledger. */",
    "  notApplicable: FrameCoverageDimension[];",
    "}",
    "",
    "export const FRAME_COVERAGE_POLICY = {",
    `  issue: ${JSON.stringify(ledger.policy.issue)},`,
    `  standard: ${JSON.stringify(ledger.policy.standard)},`,
    `  ledger: "preview/frame-coverage.ledger.json",`,
    `  recordedAt: ${JSON.stringify(ledger.baseline.recordedAt)},`,
    "  warning:",
    '    "UNTESTED means no executed case demonstrates this dimension. It is NOT a pass. Do not ' +
      'infer support from a happy-path example, a similarly-named frame, or a rendered screenshot.",',
    "  verdicts: {",
    '    covered: "An executed case proves this dimension.",',
    '    untested: "No executed case. NOT a pass — report it as UNTESTED to the user.",',
    '    "not-applicable": "The dimension cannot exist for this export; the ledger carries the written reason.",',
    "  },",
    `  requiredViewports: ${JSON.stringify(ledger.policy.viewports.required)},`,
    `  containerWidths: ${JSON.stringify(ledger.policy.viewports.containerWidths)},`,
    "  totals: {",
    `    exports: ${totals.exports},`,
    `    dimensionCells: ${totals.dimensionCells},`,
    `    covered: ${totals.covered},`,
    `    untested: ${totals.untested},`,
    `    notApplicable: ${totals.notApplicable},`,
    `    exportsWithoutFrame: ${totals.exportsWithoutFrame},`,
    "  },",
    "  dimensions: [",
    ...ledger.policy.dimensions.map(
      (dimension) =>
        `    { id: ${JSON.stringify(dimension.id)}, title: ${JSON.stringify(dimension.title)}, axis: ${JSON.stringify(dimension.axis)} },`,
    ),
    "  ],",
    "  knownGaps: [",
    ...ledger.policy.knownGaps.map(
      (gap) =>
        `    { id: ${JSON.stringify(gap.id)}, targets: ${JSON.stringify(gap.targets)}, dimensions: ${JSON.stringify(gap.dimensions)}, cases: ${JSON.stringify(gap.cases)} },`,
    ),
    "  ],",
    "} as const;",
    "",
    "export const FRAME_COVERAGE: FrameCoverageEntry[] = [",
    ...entries.map((entry) => `  ${JSON.stringify(entry)},`),
    "];",
    "",
    "const BY_NAME = new Map(FRAME_COVERAGE.map((entry) => [entry.name.toLowerCase(), entry]));",
    "",
    "export function findFrameCoverage(name: string): FrameCoverageEntry | undefined {",
    '  return BY_NAME.get(String(name ?? "").trim().toLowerCase());',
    "}",
    "",
  ];
  return `${lines.join("\n")}\n`;
}

function compact(value) {
  if (value.status === "untested") return "untested";
  if (value.status === "not-applicable") return `not-applicable:${value.via}`;
  if (value.via === "prop-evidence") return `covered:prop-evidence:${value.prop}`;
  return `covered:declared-case:${value.cases.join("+")}`;
}

function main() {
  const previous = fs.existsSync(LEDGER_PATH) ? readJson(LEDGER_PATH) : {};
  const discovery = loadDiscovery();
  const manifest = loadApiManifest();
  const caseEvidence = loadCaseEvidence();

  const caseProblems = (previous.cases ?? []).flatMap((record) => validateCase(record));
  if (caseProblems.length) {
    console.error(
      `Refusing to regenerate — ${caseProblems.length} declared case problem(s):\n` +
        caseProblems.map((problem) => `- ${problem}`).join("\n"),
    );
    process.exit(1);
  }

  const rows = deriveComponents({ discovery, manifest, caseEvidence, ledger: previous });
  const totals = totalsFor(rows);
  const geometry = geometrySweep();
  const axe = axeSweep();

  const missingFrameOwners = [
    ...new Set(rows.filter((row) => !row.hasFrame).map((row) => row.owner)),
  ].sort();

  const components = {};
  for (const row of rows) {
    const previousBaseline = previous.components?.[row.export]?.baseline;
    const count = (status) =>
      DIMENSION_IDS.filter((id) => row.dimensions[id].status === status).length;
    const covered = count("covered");
    const untested = count("untested");
    const notApplicable = count("not-applicable");
    components[row.export] = {
      group: row.group,
      owner: row.owner,
      frames: row.frames,
      ...(row.hasFrame ? {} : { hasFrame: false }),
      ...(row.embeddable ? { embeddable: true } : {}),
      // Ratchet floor for THIS export.
      //   covered        may only RISE  — losing an executed case is a regression.
      //   notApplicable  may only FALL  — converting a real dimension into a reasoned N/A is
      //                                   the weakening move, so the ceiling only tightens.
      //   untested       is INFORMATIONAL. It legitimately rises when the CONTRACT tightens
      //                  (a new public prop makes a previously N/A dimension applicable), so
      //                  gating on it would punish exactly the behaviour we want.
      baseline: resetBaseline
        ? { covered, notApplicable, untested }
        : {
            covered: Math.max(previousBaseline?.covered ?? 0, covered),
            notApplicable: Math.min(
              previousBaseline?.notApplicable ?? notApplicable,
              notApplicable,
            ),
            untested,
          },
      dimensions: Object.fromEntries(DIMENSION_IDS.map((id) => [id, compact(row.dimensions[id])])),
    };
  }

  const previousAggregate = previous.baseline ?? {};
  const ledger = {
    $schema: "../frame-coverage.ledger.schema.json",
    schemaVersion: LEDGER_SCHEMA_VERSION,
    generatedBy: "scripts/gen-frame-coverage-ledger.mjs",
    readme: [
      "Machine-readable preview-contract ledger for issue #163. GENERATED — run",
      "`pnpm gen:frame-coverage-ledger` after any public-API, frame or evidence change.",
      "",
      "Three verdicts, and only three: `covered` · `untested` · `not-applicable:<why>`.",
      "UNTESTED IS NOT A PASS. The absence of a demonstrated state is never evidence of support.",
      "",
      "`covered:prop-evidence:<prop>` — every literal branch of that public prop is enumerated in",
      "  component-case-evidence.json with rendered/test evidence that resolves on disk. It proves",
      "  the visual branch matrix ONLY — never responsive, RTL, keyboard, async or AT behaviour.",
      "`covered:declared-case:<id>` — a reviewed entry in `cases` naming a resolvable frame, a",
      "  case heading, resolvable evidence files, a reviewer and an HTTPS review link.",
      "`not-applicable:api-manifest` — the generated TypeScript surface has no such prop; the",
      "  reason is re-derived on every CI run, so it cannot rot into a false N/A.",
      "`not-applicable:reviewed` — a human waiver in `policy.notApplicable`, with a written reason.",
      "",
      "Per-dimension reasons live once in `policy.dimensions`; per-export cells stay compact.",
    ],
    policy: {
      issue: "https://github.com/godx-jp/godxjp-ui/issues/163",
      standard: "docs/FRAME-COVERAGE-STANDARD.md",
      documentation: "docs/FRAME-COVERAGE-LEDGER.md",
      verdicts: ["covered", "untested", "not-applicable"],
      viewports: {
        required: REQUIRED_VIEWPORTS,
        containerWidths: REQUIRED_CONTAINER_WIDTHS,
        note: "Issue #163 §5. An export flagged `embeddable` must additionally record every container width before `responsive` may be promoted.",
        embeddable: EMBEDDABLE_EXPORTS,
      },
      dimensions: DIMENSIONS.map((dimension) => ({
        id: dimension.id,
        title: dimension.title,
        axis: dimension.axis,
        applicability: dimension.applicability,
        promotion: dimension.promotion,
        untestedReason: dimension.untestedReason,
        ...(dimension.notApplicableReason
          ? { notApplicableReason: dimension.notApplicableReason }
          : {}),
      })),
      axes: AXES,
      notApplicable: previous.policy?.notApplicable ?? [],
      knownGaps: KNOWN_GAPS.map((gap) => ({
        ...gap,
        source: "issue #163 — Initial known gaps to encode",
        ...(previous.policy?.knownGaps?.find((entry) => entry.id === gap.id)?.resolvedBy
          ? {
              resolvedBy: previous.policy.knownGaps.find((entry) => entry.id === gap.id).resolvedBy,
            }
          : {}),
      })),
      runtimeGates: RUNTIME_GATE_SCRIPTS,
      sweeps: {
        geometry: {
          runner: "scripts/frame-geometry.mjs (pnpm check:frame-geometry)",
          baseline: "scripts/frame-geometry.baseline.json",
          recordedAt: geometry.recordedAt,
          widths: geometry.widths,
          failingFrames: geometry.failingFrames,
          failingCells: geometry.failingCells,
          byWidth: geometry.byWidth,
          note: "Recorded frame×width overflow / clipped-control failures from the shrink-only geometry baseline. NOT re-executed by this generator — the sweep needs Chromium plus a built preview. It proves the absence of overflow on the frames it swept; it is not a responsive-layout case and never promotes `responsive`.",
        },
        axe: {
          runner: "scripts/check-frame-axe.mjs (pnpm check:frame-axe)",
          baseline: "scripts/frame-axe.baseline.json",
          recordedAt: axe.recordedAt,
          failingFrames: axe.failingFrames,
          failingRules: axe.failingRules,
          note: "Recorded per-frame axe violations from the shrink-only axe baseline. NOT re-executed by this generator. An axe pass never promotes `accessibleName` or `keyboard`.",
        },
      },
    },
    infra: previous.infra ?? {
      note: "Global harness capabilities every /frame/** route provides. They make a dimension EXERCISABLE; a `covered` mark still requires an authored case that demonstrates it.",
      rtl: "?dir=rtl on any /frame/<id> flips logical CSS for the whole subtree",
      density: "?density=compact|default|comfortable on any /frame/<id>",
      theme: "?theme=light|dark on any /frame/<id>",
      locale: "?locale=ja|vi|en|ar on any /frame/<id>",
    },
    baseline: {
      recordedAt:
        resetBaseline || !previousAggregate.recordedAt
          ? new Date().toISOString().slice(0, 10)
          : previousAggregate.recordedAt,
      note: "Ratchet floor. `covered` may only rise, `knownMissingFrames` / sweep failures may only shrink. The large pre-existing `untested` backlog is RECORDED here, not passed off as coverage — it is the honest state of issue #163 and it is what the epic has to burn down.",
      exports: totals.exports,
      dimensionCells: totals.dimensionCells,
      covered: resetBaseline
        ? totals.covered
        : Math.max(previousAggregate.covered ?? 0, totals.covered),
      untested: totals.untested,
      notApplicable: totals.notApplicable,
      knownMissingFrames: missingFrameOwners,
      geometryFailingCells: resetBaseline
        ? geometry.failingCells
        : Math.min(
            previousAggregate.geometryFailingCells ?? geometry.failingCells,
            geometry.failingCells,
          ),
      axeFailingFrames: resetBaseline
        ? axe.failingFrames
        : Math.min(previousAggregate.axeFailingFrames ?? axe.failingFrames, axe.failingFrames),
    },
    cases: previous.cases ?? [],
    components,
  };

  const serialized = `${JSON.stringify(ledger, null, 2)}\n`;
  const mcpSource = renderMcpData(ledger, rows, totals);
  if (check) {
    const stale = [];
    if (!fs.existsSync(LEDGER_PATH) || fs.readFileSync(LEDGER_PATH, "utf8") !== serialized) {
      stale.push("preview/frame-coverage.ledger.json");
    }
    if (!fs.existsSync(MCP_DATA_PATH) || fs.readFileSync(MCP_DATA_PATH, "utf8") !== mcpSource) {
      stale.push("mcp/src/data/frame-coverage.generated.ts");
    }
    if (stale.length) {
      console.error(
        `${stale.join(" and ")} is stale — run \`pnpm gen:frame-coverage-ledger\`.\n` +
          "(A stale ledger means the public surface, the evidence or the ratchet floor moved.)",
      );
      process.exit(1);
    }
    console.log(
      `frame-coverage ledger current: ${totals.exports} export(s) × ${DIMENSION_IDS.length} dimension(s)`,
    );
    return;
  }
  fs.mkdirSync(path.dirname(LEDGER_PATH), { recursive: true });
  fs.writeFileSync(LEDGER_PATH, serialized);
  fs.writeFileSync(MCP_DATA_PATH, mcpSource);
  console.log(
    `wrote ${path.relative(REPO_ROOT, LEDGER_PATH)} — ${totals.exports} export(s), ` +
      `${totals.covered} covered / ${totals.untested} UNTESTED / ${totals.notApplicable} N-A ` +
      `across ${totals.dimensionCells} dimension cells`,
  );
}

main();
